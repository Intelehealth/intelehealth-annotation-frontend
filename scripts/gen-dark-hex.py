"""Generate the dark-mode rules for every hex colour class used in src (written into globals.css between markers)."""
import re, glob, colorsys, os

# Run from anywhere: python scripts/gen-dark-hex.py
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..') + '/'
pat = re.compile(r'((?:[a-z-]+:)*)(bg|text|border|ring|outline|fill|stroke|from|to|via|decoration|divide|placeholder)-\[#([0-9a-fA-F]{3,8})\]')
found = set()
for f in glob.glob(ROOT + 'src/**/*.tsx', recursive=True):
    if '/landing/' in f.replace('\\', '/'):
        continue  # the landing page is a fixed dark/light design of its own
    for m in pat.finditer(open(f, encoding='utf-8').read()):
        found.add(m.groups())


def rgb(h):
    h = h[:6] if len(h) >= 6 else ''.join(c * 2 for c in h[:3])
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def lum(c):
    f = lambda v: v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = map(f, c)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def dark_value(kind, hx):
    c = rgb(hx)
    L = lum(c)
    _, _, s = colorsys.rgb_to_hls(*c)
    sat = s > 0.25
    h = '#' + hx
    if kind in ('bg', 'from', 'to', 'via'):
        if L > 0.7:  # pale fills -> dark tint of the same hue
            return f'color-mix(in oklab, {h} {14 if sat else 6}%, var(--surface))'
        if L > 0.12:
            return None  # mid greys / colours (chart segments, legend swatches) are visible on dark as they are
        if not sat:  # ink / charcoal fills (selected states, white text on them)
            return 'var(--data)' if L < 0.03 else 'var(--active)'
        return None  # saturated accents stay
    if kind in ('text', 'fill', 'stroke', 'decoration', 'placeholder'):
        if L < 0.12:
            return 'var(--foreground)' if not sat else f'color-mix(in oklab, {h} 45%, #ffffff)'
        if L < 0.3 and not sat:
            return 'var(--muted-foreground)'
        if L < 0.3:
            return f'color-mix(in oklab, {h} 60%, #ffffff)'
        return None
    # border / ring / outline / divide
    if L > 0.6:
        return 'var(--border)' if not sat else f'color-mix(in oklab, {h} 40%, var(--surface))'
    if L < 0.05 and not sat:
        return 'var(--muted-foreground)'
    return None


PROP = {'bg': 'background-color', 'from': '--tw-gradient-from', 'to': '--tw-gradient-to', 'via': '--tw-gradient-via',
        'text': 'color', 'fill': 'fill', 'stroke': 'stroke', 'decoration': 'text-decoration-color', 'placeholder': 'color',
        'border': 'border-color', 'ring': '--tw-ring-color', 'outline': 'outline-color', 'divide': 'border-color'}
STATE = {'hover': ':hover', 'focus': ':focus', 'focus-visible': ':focus-visible', 'active': ':active', 'disabled': ':disabled'}
rules = []
for variants, kind, hx in sorted(found):
    val = dark_value(kind, hx)
    if not val:
        continue
    vs = [v for v in variants.split(':') if v]
    if any(v not in STATE and v not in ('sm', 'md', 'lg', 'xl', '2xl', 'group-hover') for v in vs) or 'dark' in vs:
        continue
    cls = (''.join(v + '\\:' for v in vs)) + f'{kind}-\\[\\#{hx}\\]'
    suffix = ''.join(STATE.get(v, '') for v in vs)
    sel = f'.dark .{cls}{suffix}'
    if 'group-hover' in vs:
        sel = f'.dark .group:hover .{cls}'
    if kind == 'placeholder':
        sel += '::placeholder'
    if kind == 'divide':
        sel += ' > :not(:last-child)'
    rules.append(f'{sel} {{ {PROP[kind]}: {val}; }}')

css_path = ROOT + 'src/app/globals.css'
css = open(css_path, encoding='utf-8').read()
start = '/* Hex classes (V9 visit page / queue) onto the theme tokens. */'
i = css.index('/* Hex classes (')
j = css.index('.dark .bg-white, .dark .hover', i)
block = start.replace('onto the theme tokens.', 'onto dark values: generated by scripts/gen-dark-hex.py from every hex class in src (re-run after adding one).') + '\n' + '\n'.join(rules) + '\n'
css = css[:i] + block + css[j:]
open(css_path, 'w', encoding='utf-8').write(css)
print(len(found), 'hex classes,', len(rules), 'dark rules')
