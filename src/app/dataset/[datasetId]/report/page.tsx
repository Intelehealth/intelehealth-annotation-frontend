'use client';

import { useEffect, useState, Suspense } from 'react';
import { useParams, useSearchParams } from 'next/navigation';
import { Printer, FileText, Loader2, AlertCircle, ArrowLeft } from 'lucide-react';
import Link from 'next/link';
import { agentAPI, type AgentPlan } from '@/lib/api/agent';
import { PlanCard } from '@/components/ai-agent/dataset-agent-chat';

function ReportInner() {
  const params = useParams();
  const search = useSearchParams();
  const datasetId = String(params?.datasetId || '');
  const planId = search?.get('planId') || '';

  const [plan, setPlan] = useState<AgentPlan | null>(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (!datasetId || !planId) {
      setError('Missing plan link. Open this report from the agent chat.');
      setLoading(false);
      return;
    }
    agentAPI
      .getPlan(datasetId, planId)
      .then((p) => {
        setPlan(p);
        setLoading(false);
      })
      .catch((e) => {
        setError(e?.response?.data?.message || 'Could not load this report.');
        setLoading(false);
      });
  }, [datasetId, planId]);

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50 print:hidden">
        <div className="flex items-center gap-2 text-muted-foreground">
          <Loader2 className="h-5 w-5 animate-spin text-blue-600" /> Loading report…
        </div>
      </div>
    );
  }

  if (error || !plan) {
    return (
      <div className="min-h-screen flex flex-col items-center justify-center gap-3 bg-slate-50 p-6 print:hidden">
        <AlertCircle className="h-8 w-8 text-red-500" />
        <p className="text-sm text-foreground">{error || 'Report not found.'}</p>
        <Link
          href={`/dataset/${datasetId}`}
          className="text-sm text-blue-600 hover:underline inline-flex items-center gap-1"
        >
          <ArrowLeft className="h-3.5 w-3.5" /> Back to dataset
        </Link>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-slate-50">
      {/* Toolbar (hidden on print) */}
      <div className="print:hidden sticky top-0 z-20 bg-classic-navy border-b border-black/20 px-4 py-3 flex items-center justify-between">
        <div className="flex items-center gap-3">
          <Link
            href={`/dataset/${datasetId}`}
            className="text-xs text-slate-200 hover:text-white inline-flex items-center gap-1"
          >
            <ArrowLeft className="h-3.5 w-3.5" /> Back
          </Link>
          <div className="h-4 w-px bg-white/20" />
          <span className="text-sm font-semibold text-white inline-flex items-center gap-1.5">
            <FileText className="h-4 w-4 text-classic-gold" /> Agent Analysis Report
          </span>
        </div>
        <button
          onClick={() => window.print()}
          className="inline-flex items-center gap-1.5 rounded-md bg-classic-gold px-3 py-1.5 text-xs font-semibold text-white hover:bg-classic-gold-hover"
        >
          <Printer className="h-3.5 w-3.5" /> Print / Save as PDF
        </button>
      </div>

      {/* Report document */}
      <div className="max-w-4xl mx-auto p-4 sm:p-6">
        <div className="rounded-xl border border-slate-200 bg-white p-4 sm:p-6 shadow-sm">
          <div className="mb-4 border-b border-slate-200 pb-3">
            <h1 className="text-lg font-bold text-classic-navy">{plan.headline || 'Agent Analysis Report'}</h1>
            <p className="text-[11px] text-classic-sub mt-1">
              {plan.generatedAt
                ? `Generated ${new Date(plan.generatedAt).toLocaleString()}`
                : 'Generated by the dataset agent'}
              {plan.model ? ` · Model: ${plan.model}` : ''}
            </p>
          </div>
          <PlanCard plan={plan} />
        </div>
      </div>
      <style jsx global>{`
        @media print {
          body { background: #fff !important; }
        }
        .print\\:hidden { display: none; }
      `}</style>
    </div>
  );
}

export default function AgentReportPage() {
  return (
    <Suspense fallback={<Loader2 className="h-6 w-6 animate-spin text-blue-600 mx-auto mt-20" />}>
      <ReportInner />
    </Suspense>
  );
}
